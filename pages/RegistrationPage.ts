import { Page, Locator } from '@playwright/test';
import { Patient } from '../utils/testData';

export class RegistrationPage {
  readonly page: Page;
  readonly firstNameInput: Locator;
  readonly familyNameInput: Locator;
  readonly sexGroup: Locator;
  readonly birthDayInput: Locator;
  readonly birthMonthInput: Locator;
  readonly birthYearInput: Locator;
  readonly birthDateError: Locator;
  readonly openmrsIdAutoGenerated: Locator;
  readonly registerButton: Locator;

  constructor(page: Page) {
    this.page = page;
    this.firstNameInput = page.getByRole('textbox', { name: 'First Name' });
    this.familyNameInput = page.getByRole('textbox', { name: 'Family Name' });
    this.sexGroup = page.getByRole('group', { name: 'Sex' });
    this.birthDayInput = page.getByRole('spinbutton', { name: 'day, Date of birth' });
    this.birthMonthInput = page.getByRole('spinbutton', { name: 'month, Date of birth' });
    this.birthYearInput = page.getByRole('spinbutton', { name: 'year, Date of birth' });
    this.birthDateError = page.getByText(/^Birthday cannot be/);
    this.openmrsIdAutoGenerated = page.getByText('Auto-generated');
    this.registerButton = page.getByRole('button', { name: 'Register patient' });
  }

  async selectSex(sex: Patient['sex']) {
    // Click the visible label: the styled radio circle covers the real input, so check() is blocked.
    // exact, because "Male" would also match "Female"
    await this.sexGroup.getByText(sex, { exact: true }).click();
  }

  async fillPatient(patient: Patient) {
    await this.firstNameInput.fill(patient.givenName);
    await this.familyNameInput.fill(patient.familyName);
    await this.selectSex(patient.sex);
    // The date fields are segmented inputs, so type into them like a user would
    await this.birthDayInput.pressSequentially(patient.birthDay);
    await this.birthMonthInput.pressSequentially(patient.birthMonth);
    await this.birthYearInput.pressSequentially(patient.birthYear);
  }

  async register() {
    // The Identifiers section loads after the rest of the form, so wait for the OpenMRS ID before saving
    await this.openmrsIdAutoGenerated.waitFor();
    await this.registerButton.click();
    await this.page.waitForURL(/\/patient\/[0-9a-f-]+\/chart/);
  }

  getPatientUuid() {
    const afterPatient = this.page.url().split('/patient/')[1];
    return afterPatient.split('/')[0];
  }
}
